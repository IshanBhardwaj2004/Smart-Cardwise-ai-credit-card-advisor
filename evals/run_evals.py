"""
Eval runner: runs the assignment's 20 questions + the stress set, checks every answer, logs everything.
Every answer goes to eval_results.json (its request_id points to the full evidence in traces/),
and to docs/question_log.md: one readable entry per question (answer, cards, what was sent to
the server, data warnings, auto-check), with a line for your own verdict.

  python -m evals.run_evals              # both sets
  python -m evals.run_evals core         # only the assignment's 20
  python -m evals.run_evals stress       # only the stress set

Mock mode by default (no network). With the real server + Qwen:
  PowerShell:  $env:MCP_MODE="live"; $env:LLM_MODE="live"; python -m evals.run_evals
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("MCP_MODE", "mock")
os.environ.setdefault("LLM_MODE", "mock")

from app.config import config                 # noqa: E402
from app.core.pipeline import Pipeline        # noqa: E402
from evals.questions import QUESTIONS, STRESS  # noqa: E402

OUT = "eval_results.json"
LOG = os.path.join("docs", "question_log.md")


def _outcome(reply) -> str:
    if reply.refused:
        return "refuse"
    return "ask" if reply.clarifying else "answer"


def _issues(item, reply) -> list[str]:
    issues = []
    got = _outcome(reply)
    expected = item.get("expect") or ("refuse" if item.get("expect_refuse") else
                                      "ask" if item.get("expect_clarify") else "answer")
    if got != expected:
        issues.append(f"expected '{expected}', got '{got}'")
    if item.get("expect_intent") and not reply.refused and reply.intent.value != item["expect_intent"]:
        issues.append(f"intent is {reply.intent.value}, expected {item['expect_intent']}")
    for bad in item.get("must_not", []):
        if bad.lower() in reply.reply.lower():
            issues.append(f"reply contains '{bad}'")
    if reply.fallback_table and config.LLM_MODE == "live":
        issues.append("LLM reply failed or was blocked by the output guard, template reply shown")
    return issues


def _trace(request_id: str) -> dict:
    path = os.path.join(config.TRACE_DIR, f"{request_id}.json")
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def _write_log(entries: list[dict]) -> None:
    """Readable log for review: question -> answer -> evidence, with a line for the reviewer's verdict."""
    lines = ["# Question log", "",
             f"Run with MCP: {config.MCP_MODE}, LLM: {config.LLM_MODE}. Generated by `python -m evals.run_evals`.",
             "For each answer, fill in the verdict: right / wrong / made up / missing / misleading.",
             "If it is not right, copy it to failures.md with the cause (model / MCP tool / data).", ""]
    for e in entries:
        trace = _trace(e["request_id"])
        lines += [f"### {e['n']}. ({e['category']}) {e['question']}", "",
                  "**Answer:** " + e["answer"].replace("\n", " "), ""]
        for c in e["cards"]:
            figures = ", ".join(f"{m['label']} {m['value']}" for m in c["metrics"])
            lines.append(f"- Card: {c['name']}" + (f" [{c['badge']}]" if c.get("badge") else "") + (f": {figures}" if figures else ""))
        for call in trace.get("tool_calls", []):
            lines.append(f"- Sent to server: `{call['tool']}` `{json.dumps(call['arguments'], ensure_ascii=False)}`")
        for flag in trace.get("validation_flags", []):
            who = "shown to user" if flag.get("warn_user") else "evidence only"
            lines.append(f"- Data check ({flag['suspected_fault']}, {who}): {flag['problem']}")
        if trace.get("llm_raw_reply") is not None or trace.get("notes"):
            used = ("template reply (mock mode)" if config.LLM_MODE == "mock" else
                    "template reply (LLM failed or was blocked)" if e.get("template_reply") else "LLM")
            lines.append(f"- Reply written by: {used}")
        lines += [f"- Auto-check: {'PASS' if not e['issues'] else 'FAIL: ' + '; '.join(e['issues'])}",
                  f"- Evidence: `{os.path.relpath(e['trace_file'])}`",
                  "- **Your verdict:** ", ""]
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def run(which: str = "all") -> bool:
    live = config.MCP_MODE == "live"
    sets = {"core": [dict(q, cat=q.get("cat", "assignment")) for q in QUESTIONS], "stress": STRESS}
    items = sets["core"] + sets["stress"] if which == "all" else sets[which]
    pipe = Pipeline()
    log, by_cat, fails = [], Counter(), Counter()
    print(f"Running {len(items)} questions (MCP: {config.MCP_MODE}, LLM: {config.LLM_MODE})\n")

    for n, item in enumerate(items, 1):
        question = item.get("q_live", item["q"]) if live else item["q"]
        session = item.get("session")
        reply = pipe.handle(question, f"eval-{session}" if session else None)
        issues = _issues(item, reply)
        by_cat[item["cat"]] += 1
        fails[item["cat"]] += bool(issues)

        print(f"[{'FAIL' if issues else 'PASS'}] {n:>2}. ({item['cat']}) {question}")
        print(f"      -> {reply.reply[:200].replace(chr(10), ' / ')}")
        for c in reply.cards:
            print(f"         card: {c.name} | " + ", ".join(f"{m.label} {m.value}" for m in c.metrics))
        for issue in issues:
            print(f"      !! {issue}")

        log.append({"n": n, "category": item["cat"], "question": question, "answer": reply.reply,
                    "outcome": _outcome(reply), "cards": [c.model_dump() for c in reply.cards],
                    "note": reply.note, "suspect_data": reply.suspect_data, "issues": issues,
                    "template_reply": reply.fallback_table, "request_id": reply.request_id, "trace_file": f"{config.TRACE_DIR}/{reply.request_id}.json"})

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(log, f, ensure_ascii=False, indent=2)

    _write_log(log)

    print("\n" + "=" * 60)
    for cat in by_cat:
        print(f"  {cat:<14} {by_cat[cat] - fails[cat]}/{by_cat[cat]} passed")
    total_fail = sum(fails.values())
    print(f"RESULT: {len(items) - total_fail} passed, {total_fail} failed out of {len(items)}")
    print(f"All answers saved to {OUT} and {LOG}")
    return total_fail == 0


if __name__ == "__main__":
    choice = sys.argv[1] if len(sys.argv) > 1 else "all"
    sys.exit(0 if run(choice) else 1)